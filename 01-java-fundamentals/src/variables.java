public class variables {

    // In Java, we have some primitive variable types:
    int age = 22;
    double price = 19.99;
    boolean active = true;
    char grade = 'A';

    // And reference types:
    String name = "Rafael";

    // Primitive types you should know:
    byte x_byte = 10;
    short x_short = 100;
    int x_int = 1000;
    long x_long = 100000L;
    float x_float = 10.5f;
    double x_double = 10.5;
    char x_char = 'A';
    boolean x_bool = true;
}
