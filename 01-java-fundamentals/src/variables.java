public class Variables {

    // In Java, we have some primitive variable types:
    int age = 22;
    double price = 19.99;
    boolean active = true;
    char grade = 'A';

    // And reference types:
    String name = "Rafael";

    // Primitive types you should know:
    byte xByte = 10;
    short xShort = 100;
    int xInt = 1000;
    long xLong = 100000L;
    float xFloat = 10.5f;
    double xDouble = 10.5;
    char xChar = 'A';
    boolean xBool = true;
}
